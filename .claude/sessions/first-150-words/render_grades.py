#!/usr/bin/env python3
"""Render grades.md from grades.json (rubric scores per page), in pages.json group order.

Usage (from the repo root): python3 .claude/sessions/first-150-words/render_grades.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAGES = json.loads((HERE / "pages.json").read_text(encoding="utf-8"))
GRADES = {g["n"]: g for g in json.loads((HERE / "grades.json").read_text(encoding="utf-8"))}
OUT = HERE / "grades.md"

RUBRIC = [
    ("A", "First paragraph says what the page is, what it covers, and what you can do after reading"),
    ("B", "Plain, descriptive title (not clever)"),
    ("C", "Focused on one topic"),
    ("D", "First 150 words explain what the page is about and what it answers"),
]


def main():
    all_ns = [p["n"] for g in PAGES["groups"] for p in g["pages"]]
    missing = sorted(set(all_ns) - set(GRADES))
    assert not missing, f"missing grades for {missing}"
    for g in GRADES.values():
        assert g["total"] == sum(g[k] for k, _ in RUBRIC), g["n"]

    out = ["# First 150 words: rubric grades", "",
           "Each criterion scores 0–2 (8 max). Generated by `render_grades.py` from `grades.json`.", ""]
    out += [f"- **{k}.** {desc}" for k, desc in RUBRIC]
    out += ["", "Grades reflect the pages after PR #758 merged (#1, #3, #25, #27 re-graded 2026-10-20).", ""]

    # Summary, lowest first
    out += ["## Summary (lowest total first)", "", "| # | Page | A | B | C | D | Total |", "|---|---|---|---|---|---|---|"]
    for g in sorted(GRADES.values(), key=lambda g: (g["total"], g["n"])):
        out.append(f"| {g['n']} | {g['title']} | {g['A']} | {g['B']} | {g['C']} | {g['D']} | **{g['total']}** |")
    avg = {k: sum(g[k] for g in GRADES.values()) / len(GRADES) for k, _ in RUBRIC}
    out += ["", "Average per criterion: " + ", ".join(f"{k} {v:.1f}" for k, v in avg.items()), ""]

    # Per page, grouped
    for grp in PAGES["groups"]:
        out += [f"## {grp['title']}", ""]
        for p in grp["pages"]:
            g = GRADES[p["n"]]
            out.append(f"### {p['n']}. {p['title']} ({g['total']}/8)")
            for k, _ in RUBRIC:
                out.append(f"- **{k} ({g[k]}):** {g[k + '_why']}")
            out.append(f"- **Biggest fix:** {g['biggest_fix']}")
            out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.name}: {len(GRADES)} pages")


if __name__ == "__main__":
    main()
