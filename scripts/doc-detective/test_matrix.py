#!/usr/bin/env python3
"""The test matrix: every claim the docs tests check, where, how often CI runs it, and the evidence
from its last saved run. Generated from the pages' test markup, test-pages.json, and the saved results
in reports/, so it can't drift from them: --check fails when TEST-MATRIX.md is out of date.

Usage:
  test_matrix.py                write TEST-MATRIX.md
  test_matrix.py --check        exit 1 if TEST-MATRIX.md isn't what this would write
  test_matrix.py save PAGE      after a run: write reports/<slug>.json (each test's result, the commit,
                                and when it ran) from output/, then rewrite TEST-MATRIX.md. run.sh does
                                this with DOC_TESTS_SAVE_REPORT=1, after the leak check passes.
  test_matrix.py slug PAGE      print the name saved reports use for PAGE
"""

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.join(HERE, ".deps"), HERE]

from codetests import markup, provenance, record, settings  # noqa: E402
from codetests.reports import doc_detective  # noqa: E402
import plan_runs  # noqa: E402

MATRIX_FILE = os.path.join(HERE, "TEST-MATRIX.md")
REPORTS_DIR = os.path.join(HERE, "reports")
CADENCE = {1: "weekly", 2: "monthly", 3: "on demand"}
KINDS = {
    "": "documented output",
    "documents": "portfolio documents",
    "fingerprint": "fingerprint (strict mode)",
    "classification": "classification",
}


def slug(page):
    """The page path as a file name, for example docs-senseml-reference-concepts-file-types."""
    return re.sub(r"[^a-z0-9]+", "-", page[:-3].lower() if page.endswith(".md") else page.lower()).strip("-")


def tests(page_path):
    """[(test_id, kind, claim, fixtures)] for a page, in page order."""
    page = markup.parse_page(os.path.join(settings.REPO_ROOT, page_path))
    rows = [(t.line, t.test_id, "UI", t.description, []) for t in page.ui_tests]
    for t in page.code_tests.values():
        kind = KINDS.get(t.compare, t.compare)
        if t.row:
            kind += f", table row {t.row.split(':')[0]}"
        rows.append((t.line, t.test_id, kind, t.description, list(t.fixtures)))
    return [row[1:] for row in sorted(rows, key=lambda r: r[0])]


def saved(page_path, reports_dir=REPORTS_DIR):
    """The page's saved results (reports/<slug>.json), or None."""
    path = os.path.join(reports_dir, f"{slug(page_path)}.json")
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def render(entries=None, reports_dir=REPORTS_DIR):
    """TEST-MATRIX.md's text. Deterministic: only committed inputs, no clock."""
    entries = plan_runs.load() if entries is None else entries
    lines = [
        "# Docs test matrix",
        "",
        "Generated by `scripts/doc-detective/test_matrix.py` from the pages' test markup, `test-pages.json`, and the saved results in `reports/`. Don't edit it by hand: run `python3 scripts/doc-detective/test_matrix.py` (a unit test fails when it's out of date).",
        "",
        "**Last saved run** is the evidence: the result of the most recent run someone saved with `DOC_TESTS_SAVE_REPORT=1`, the commit it tested, and a link to its HTML report. CI runs don't save; they open issues when a claim stops holding.",
        "",
        "| Page | Priority | Test | Kind | Claim | Fixture | Last saved run |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in entries:
        page = entry["page"]
        result = saved(page, reports_dir)
        evidence = "none saved"
        if result:
            stamp = f"{result['tested_at'][:10]}, commit {result['commit']}" + (" (uncommitted changes)" if result["uncommitted"] else "")
            report = os.path.relpath(os.path.join(reports_dir, result["report"]), HERE)
        for test_id, kind, claim, fixtures in tests(page):
            if result:
                status = result["tests"].get(test_id, "not in that run")
                evidence = f"{status}, {stamp}, [report]({report})"
            lines.append(f"| {cell(os.path.basename(page))} | {entry['priority']} ({CADENCE[entry['priority']]}) | `{test_id}` | {cell(kind)} | "
                         f"{cell(claim) or '(no description)'} | {', '.join(f'`{x}`' for x in fixtures)} | {evidence} |")
    return "\n".join(lines) + "\n"


def write(text=None):
    with open(MATRIX_FILE, "w", encoding="utf-8") as f:
        f.write(render() if text is None else text)


def save(page_path, output_dir=settings.OUTPUT_DIR, reports_dir=REPORTS_DIR):
    """Write reports/<slug>.json from a run's output: each test's status, plus the run's provenance."""
    page = markup.parse_page(os.path.join(settings.REPO_ROOT, page_path))
    ui = doc_detective.load_results(output_dir)
    by_id = {r["test_id"]: r for r in record.load_all(os.path.join(output_dir, "code-tests"))}
    statuses = {t.test_id: ("fail" if t.test_id not in ui or len(ui[t.test_id]["steps"]) < t.steps else ui[t.test_id]["status"])
                for t in page.ui_tests}
    statuses.update({t: by_id[t]["status"] if t in by_id else "fail" for t in page.code_tests})
    name = slug(page_path)
    result = {
        "page": page_path,
        "report": f"{name}.html",
        **provenance.for_run(output_dir, page_path),
        "overall": "fail" if "fail" in statuses.values() else "warn" if "warn" in statuses.values() else "pass",
        "tests": statuses,
    }
    os.makedirs(reports_dir, exist_ok=True)
    path = os.path.join(reports_dir, f"{name}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2)
        f.write("\n")
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", nargs="?", choices=["save", "slug"])
    parser.add_argument("page", nargs="?")
    parser.add_argument("--check", action="store_true", help="Exit 1 if TEST-MATRIX.md is out of date")
    args = parser.parse_args()
    if args.command and not args.page:
        parser.error(f"{args.command} needs PAGE")
    if args.command == "slug":
        print(slug(args.page))
        return 0
    if args.command == "save":
        print(f"Saved the results to {os.path.relpath(save(args.page), settings.REPO_ROOT)}")
    text = render()
    if args.check:
        current = open(MATRIX_FILE, encoding="utf-8").read() if os.path.isfile(MATRIX_FILE) else ""
        if current != text:
            print("FAIL TEST-MATRIX.md is out of date. Run: python3 scripts/doc-detective/test_matrix.py", file=sys.stderr)
            return 1
        print("PASS TEST-MATRIX.md is up to date", file=sys.stderr)
        return 0
    write(text)
    print(f"Wrote {os.path.relpath(MATRIX_FILE, settings.REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
