#!/usr/bin/env python3
"""The test matrix: every claim the docs tests check, where, how often CI runs it, and the evidence
from its last saved run, then every record-only claim and its evidence record. Generated from the pages'
test markup, test-pages.json, the saved results in reports/, and the records in testable-claims/, so it can't
drift from them: --check fails when TEST-MATRIX.md is out of date.

Usage:
  test_matrix.py                write TEST-MATRIX.md
  test_matrix.py --check        exit 1 if TEST-MATRIX.md isn't what this would write
  test_matrix.py save PAGE      after a run: write reports/<slug>.json (each test's result, including
                                other runners', the commit, and when it ran) from output/, then
                                rewrite TEST-MATRIX.md. run.sh does
                                this with DOC_TESTS_SAVE_REPORT=1, after the leak check passes.
  test_matrix.py slug PAGE      print the name saved reports use for PAGE
"""

import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [os.path.join(HERE, ".deps"), HERE]

from codetests import evidence, kinds, markup, provenance, record, results, settings  # noqa: E402
from codetests.reports import doc_detective  # noqa: E402
import plan_runs  # noqa: E402

MATRIX_FILE = os.path.join(HERE, "TEST-MATRIX.md")
REPORTS_DIR = os.path.join(HERE, "reports")
CADENCE = {1: "weekly", 2: "monthly", 3: "on demand"}


def slug(page):
    """The page path as a file name, for example docs-senseml-reference-concepts-file-types."""
    return re.sub(r"[^a-z0-9]+", "-", page[:-3].lower() if page.endswith(".md") else page.lower()).strip("-")


def tests(page_path):
    """[(test_id, kind, claim, fixtures)] for a page, in page order."""
    page = markup.parse_page(os.path.join(settings.REPO_ROOT, page_path))
    rows = [(t.line, t.test_id, "UI", t.description, []) for t in page.ui_tests]
    for t in page.code_tests.values():
        kind = kinds.of(t).LABEL
        if t.row:
            kind += f", table row {t.row.split(':')[0]}"
        rows.append((t.line, t.test_id, kind, t.description, list(t.fixtures)))
    return [row[1:] for row in sorted(rows, key=lambda r: r[0])]


def saved(page_path, reports_dir=REPORTS_DIR):
    """The page's saved results (reports/<slug>.json), or None."""
    path = os.path.join(reports_dir, f"{slug(page_path)}.json")
    if not os.path.isfile(path):
        return None
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ")


def evidence_rows(evidence_dir=evidence.EVIDENCE_DIR):
    """The record-only section's lines, one row per evidence record."""
    lines = [
        "",
        "## Record-only claims",
        "",
        "Claims tested by hand and recorded rather than run from the page: the page's section carries a `tested claims` comment listing their IDs, and each ID has an evidence record in `testable-claims/pr-<number>-<feature>/`, grouped by the docs PR that tested it, with the configs, documents, and responses that ran. Nothing reruns them; CI warns when a record's newest run is more than six months old.",
        "",
    ]
    records = evidence.load_all(evidence_dir)
    if not records:
        return lines + ["None yet."]
    lines += ["| Docs PR | Page | Section | Claim ID | Kind | Claim | Verdict | Evidence |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for path, r in records:
        runs = r["runs"]
        where = ", ".join(sorted({f"{run['environment']} ({run['account'].replace('_', ' ')} account)" for run in runs}))
        record = os.path.relpath(path, HERE)
        lines.append(f"| #{r['docs_pr']} | {cell(os.path.basename(r['page']))} | {cell(r['section'])} | `{r['claim_id']}` | {cell(r['claim_kind'])} | "
                     f"{cell(r['claim'])} | {r['verdict'].replace('_', ' ')} | {evidence.newest_run(r)}, {len(runs)} runs, {where}, [record]({record}) |")
    return lines


def render(entries=None, reports_dir=REPORTS_DIR, evidence_dir=evidence.EVIDENCE_DIR):
    """TEST-MATRIX.md's text. Deterministic: only committed inputs, no clock."""
    entries = plan_runs.load() if entries is None else entries
    lines = [
        "# Docs test matrix",
        "",
        "Generated by `scripts/doc-detective/test_matrix.py` from the pages' test markup, `test-pages.json`, the saved results in `reports/`, and the evidence records in `testable-claims/`. Don't edit it by hand: run `python3 scripts/doc-detective/test_matrix.py` (a unit test fails when it's out of date).",
        "",
        "**Last saved run** is the evidence: the result of the most recent run someone saved with `DOC_TESTS_SAVE_REPORT=1`, the commit it tested, and a link to its HTML report. CI runs don't save; they open issues when a claim stops holding.",
        "",
        "| Page | Priority | Test | Kind | Claim | Fixture | Last saved run |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in entries:
        page = entry["page"]
        result = saved(page, reports_dir)
        last_run = "none saved"
        if result:
            stamp = f"{result['tested_at'][:10]}, commit {result['commit']}" + (" (uncommitted changes)" if result["uncommitted"] else "")
            report = os.path.relpath(os.path.join(reports_dir, result["report"]), HERE)
        rows = tests(page) + [(r["test_id"], f"{r['kind']} ({r['runner']})", r["claim"], []) for r in (result or {}).get("other", [])]
        for test_id, kind, claim, fixtures in rows:
            if result:
                status = result["tests"].get(test_id, "not in that run")
                last_run = f"{status}, {stamp}, [report]({report})"
            lines.append(f"| {cell(os.path.basename(page))} | {entry['priority']} ({CADENCE[entry['priority']]}) | `{test_id}` | {cell(kind)} | "
                         f"{cell(claim) or '(no description)'} | {', '.join(f'`{x}`' for x in fixtures)} | {last_run} |")
    return "\n".join(lines + evidence_rows(evidence_dir)) + "\n"


def write(text=None):
    with open(MATRIX_FILE, "w", encoding="utf-8") as f:
        f.write(render() if text is None else text)


def save(page_path, output_dir=settings.OUTPUT_DIR, reports_dir=REPORTS_DIR):
    """Write reports/<slug>.json from a run's output: each test's status, other runners' results, and
    the run's provenance."""
    page = markup.parse_page(os.path.join(settings.REPO_ROOT, page_path))
    other = results.load_other(output_dir)
    page_results = results.for_page(page, doc_detective.load_results(output_dir),
                                    record.load_all(os.path.join(output_dir, "code-tests")), other)
    name = slug(page_path)
    saved_result = {
        "page": page_path,
        "report": f"{name}.html",
        **provenance.for_run(output_dir, page_path),
        "overall": results.overall(page_results),
        "tests": {r["test_id"]: r["status"] for r in page_results},
        # Other runners' tests aren't in the page's markup, so the matrix lists them from here
        **({"other": [{k: r[k] for k in ("test_id", "runner", "kind", "claim", "status")} for r in other]} if other else {}),
    }
    os.makedirs(reports_dir, exist_ok=True)
    path = os.path.join(reports_dir, f"{name}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(saved_result, f, indent=2)
        f.write("\n")
    return path


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", nargs="?", choices=["save", "slug"])
    parser.add_argument("page", nargs="?")
    parser.add_argument("--check", action="store_true", help="Exit 1 if TEST-MATRIX.md is out of date")
    args = parser.parse_args()
    if args.command and not args.page:
        parser.error(f"{args.command} needs PAGE")
    if args.command == "slug":
        print(slug(args.page))
        return 0
    if args.command == "save":
        print(f"Saved the results to {os.path.relpath(save(args.page), settings.REPO_ROOT)}")
    text = render()
    if args.check:
        current = open(MATRIX_FILE, encoding="utf-8").read() if os.path.isfile(MATRIX_FILE) else ""
        if current != text:
            print("FAIL TEST-MATRIX.md is out of date. Run: python3 scripts/doc-detective/test_matrix.py", file=sys.stderr)
            return 1
        print("PASS TEST-MATRIX.md is up to date", file=sys.stderr)
        return 0
    write(text)
    print(f"Wrote {os.path.relpath(MATRIX_FILE, settings.REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
