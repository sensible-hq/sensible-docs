#!/usr/bin/env python3
"""Render registry.yaml as REVIEW.md: one table per guide file, for a human to review.

REVIEW.md is generated; edit registry.yaml and re-run this script. A test fails if the
committed REVIEW.md doesn't match the registry.

Usage: review_table.py [--check]
"""
import sys
from collections import Counter
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REGISTRY = HERE / "registry.yaml"
OUT = HERE / "REVIEW.md"
GUIDE_LINK = "../../.claude/style-guide/"


def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def enforcement(rule, agent_only=()):
    if "vale" in rule:
        checks = rule["vale"] if isinstance(rule["vale"], list) else [rule["vale"]]
        return "Vale: " + ", ".join(
            f"`{c}`" + (" (agent-added lines only)" if c in agent_only else "") for c in checks)
    if "human" in rule:
        return "Human: " + cell(rule["human"])
    if "none-yet" in rule:
        return "**Not enforced yet**" + (": " + cell(rule["none-yet"]) if rule["none-yet"] else "")
    return "?"


def location(rule):
    if "at" not in rule:
        return f"*(no guide rule)* {cell(rule.get('basis', ''))}"
    file, _, anchor = rule["at"].partition("#")
    label = rule.get("item") or rule.get("row") or anchor.replace("-", " ")
    return f"[{cell(label)}]({GUIDE_LINK}{file}#{anchor})"


def render(registry):
    rules = registry.get("rules") or []
    agent_only = set(registry.get("agent_only_rules") or [])
    status = Counter(r.get("status", "reviewed") for r in rules)
    kinds = Counter(("vale" if "vale" in r else "human" if "human" in r else "none-yet") for r in rules)
    lines = [
        "# Style guide ↔ Vale: rule mapping for review",
        "",
        "<!-- GENERATED by scripts/style_sync/review_table.py from registry.yaml. Do not edit. -->",
        "",
        "Each row is one style-guide rule and how it's enforced. To review a row, check the",
        "enforcement is right, then delete its `status: draft` line in `registry.yaml` (or fix the",
        "entry) and re-run `python scripts/style_sync/review_table.py`.",
        "",
        f"**{len(rules)} rules:** {kinds['vale']} enforced by Vale, {kinds['human']} human-only, "
        f"{kinds['none-yet']} not enforced yet. **Status:** "
        + ", ".join(f"{n} {s}" for s, n in sorted(status.items())) + ".",
        "",
    ]
    groups = {}
    for r in rules:
        groups.setdefault(r["at"].split("#")[0] if "at" in r else "Vale rules with no guide rule", []).append(r)
    for name, members in groups.items():
        lines += [f"## {name}", "", "| Status | Rule | Enforced by | Note | ID |", "| --- | --- | --- | --- | --- |"]
        for r in members:
            st = r.get("status", "reviewed")
            lines.append(f"| {'⚠️ ' if st == 'draft' else ''}{st} | {location(r)} | {enforcement(r, agent_only)} | "
                         f"{cell(r.get('note', ''))} | `{r['id']}` |")
        lines.append("")
    return "\n".join(lines)


def main(argv):
    text = render(yaml.safe_load(REGISTRY.read_text(encoding="utf-8")))
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("REVIEW.md is stale; run scripts/style_sync/review_table.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(Path.cwd()) if OUT.is_relative_to(Path.cwd()) else OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
